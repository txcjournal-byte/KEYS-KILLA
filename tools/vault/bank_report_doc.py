#!/usr/bin/env python3
"""Write docs/VAULT_BANK_REPORT.md from the full assembly report of `VaultBankGen -recipe all -qa -report full.md`.

usage: python3 tools/vault/bank_report_doc.py full.md docs/VAULT_BANK_REPORT.md

Keeps the summary, the per-category table and one line per SHIPPED preset (the full report also lists every rejected
candidate and is ~1 MB, so it stays out of the repo).
"""
import sys


def main():
    src, dst = sys.argv[1:3]
    lines = open(src, encoding="utf-8").read().split("\n")
    out = []
    i = 0
    # summary + per-category table: everything up to the "Every candidate" heading
    while i < len(lines) and not lines[i].startswith("## Every candidate"):
        out.append(lines[i])
        i += 1
    rows = [l for l in lines[i:] if l.startswith("| cv.")]
    head = None
    for l in lines[i:]:
        if l.startswith("| id |"):
            head = [c.strip() for c in l.strip().strip("|").split("|")]
            break
    if head is None:
        sys.exit("no candidate table in " + src)
    keep = ["id", "name", "recipe", "parts", "gain dB", "H1 dB", "2-5k %", ">8k %", "centroid", "tail s", "vel dB", "phrase dB", "nearest (dist)"]
    idx = [head.index(k) for k in keep if k in head]
    ok = head.index("result")
    shipped = []
    for l in rows:
        c = [x.strip() for x in l.strip().strip("|").split(" | ")]
        if len(c) == len(head) and c[ok] == "ok":
            shipped.append(c)
    shipped.sort(key=lambda c: (c[0].split(".")[1], int(c[0].split(".")[2])))
    out[0] = "# CHROME VAULT v2 factory bank - QC report"
    out.append("## Shipped presets (" + str(len(shipped)) + ")")
    out.append("")
    out.append("Generated by `tools/vault/bank_report_doc.py` from the assembly report - do not edit by hand. `phrase dB` = the listening "
               "phrase's peak before the safety limiter, dB over its 0.89 ceiling (negative = headroom).")
    out.append("")
    out.append("| " + " | ".join(head[k] for k in idx) + " |")
    out.append("|" + "---|" * len(idx))
    for c in shipped:
        out.append("| " + " | ".join(c[k] for k in idx) + " |")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", dst, len(shipped), "presets")


if __name__ == "__main__":
    main()
